pub fn dispatch(store: &mut Store, command: &[u8], args: &[Frame<'_>]) -> SenkoResult<Response> {
    store.record_command();
    if (command.eq_ignore_ascii_case(b"PFDEBUG") || command.eq_ignore_ascii_case(b"PFSELFTEST"))
        && !senko_store::hll::debug_commands_enabled()
    {
        return Err(unknown_command(command));
    }
    if command.len() == 3 && command.eq_ignore_ascii_case(b"GET") {
        return basic::get(store, args);
    }
    if command.len() == 3 && command.eq_ignore_ascii_case(b"SET") {
        return basic::set(store, args);
    }
    let Some(handler) = COMMANDS.get(command) else {
        return Err(unknown_command(command));
    };
    handler(store, args)
}

fn unknown_command(command: &[u8]) -> SenkoError {
    let command = String::from_utf8_lossy(command);
    SenkoError::ProtocolMessage(CompactString::from(format!(
        "ERR unknown command '{command}'"
    )))
}
